const form = document.getElementById("predict-form");
const btn = document.getElementById("submit-btn");
const empty = document.getElementById("empty-state");
const result = document.getElementById("result");
const errorBox = document.getElementById("error");

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  errorBox.classList.add("hidden");
  result.classList.add("hidden");
  btn.disabled = true;
  btn.innerHTML = "Analysing profile <span>…</span>";
  const payload = {
    attendance: document.getElementById("attendance").value,
    hours_studied: document.getElementById("hours").value,
    previous_scores: document.getElementById("previous").value,
    model: document.getElementById("model").value
  };
  try {
    const response = await fetch("/api/predict", {
      method: "POST",
      headers: {"Content-Type": "application/json"},
      body: JSON.stringify(payload)
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || "Something went wrong.");
    empty.classList.add("hidden");
    result.classList.remove("hidden");
    const pred = document.getElementById("prediction");
    pred.textContent = data.prediction;
    pred.className = "prediction " + data.prediction.toLowerCase();
    document.getElementById("confidence").textContent = data.confidence + "%";
    document.getElementById("confidence-bar").style.width = data.confidence + "%";
    document.getElementById("probabilities").innerHTML = "";
    ["Low", "Medium", "High"].forEach(label => {
      const value = data.probabilities[label] ?? 0;
      const row = document.createElement("div");
      row.className = "prob-row";
      row.innerHTML = `<span>${label}</span><div class="mini-bar"><i style="width:${value}%"></i></div><b>${value}%</b>`;
      document.getElementById("probabilities").appendChild(row);
    });
    document.getElementById("result-note").textContent = `Prediction generated by ${data.model}. Confidence is the model's probability estimate, not a guarantee of correctness.`;
  } catch (err) {
    errorBox.textContent = err.message;
    errorBox.classList.remove("hidden");
    empty.classList.remove("hidden");
  } finally {
    btn.disabled = false;
    btn.innerHTML = 'Predict performance <span>↗</span>';
  }
});
